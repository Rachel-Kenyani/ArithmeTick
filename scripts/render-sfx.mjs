PENTA.forEach((f, i) => { SOUNDS[`snap${i}`] = [tone(f * 2, 0.05, "square", 0.12, { toFreq: f }), tone(f, 0.18, "triangle", 0.35, { delay: 0.015 })]; });
export const HOLD_STEPS = 6;
for (let i = 0; i < HOLD_STEPS; i++) SOUNDS[`holdTick${i}`] = [tone(300 + (i / (HOLD_STEPS - 1)) * 600, 0.06, "sine", 0.15)];

mkdirSync("assets/sfx", { recursive: true });
for (const [name, tones] of Object.entries(SOUNDS)) writeFileSync(`assets/sfx/${name}.wav`, wav(render(tones)));

const lines = Object.keys(SOUNDS).map((n) => `  ${n}: require("../../../assets/sfx/${n}.wav"),`);
writeFileSync(
  "src/services/audio/sfxAssets.ts",
  `/* Generated by scripts/render-sfx.mjs — do not edit. */\nexport const SFX_ASSETS = {\n${lines.join("\n")}\n} as const;\n\nexport type SfxName = keyof typeof SFX_ASSETS;\nexport const HOLD_STEPS = ${HOLD_STEPS};\n`,
);
