/**
 * Renders the web app's Web Audio recipes (arithmetick/lib/audio.ts) to 16-bit mono WAVs in assets/sfx/,
 * so the native app sounds identical. Re-run after changing a recipe:  node scripts/render-sfx.mjs
 * Then regenerate src/services/audio/sfxAssets.ts (this script writes it too).
 */
import { mkdirSync, writeFileSync } from "node:fs";

const RATE = 44100;
const MASTER = 0.55;
const PENTA = [523.25, 587.33, 659.25, 783.99, 880.0, 1046.5, 1174.66, 1318.51, 1567.98, 1760.0];

/** Exponential ramp like AudioParam.exponentialRampToValueAtTime. */
const expRamp = (a, b, t) => a * Math.pow(b / a, Math.min(1, Math.max(0, t)));

function osc(type, phase) {
  const p = phase - Math.floor(phase);
  switch (type) {
    case "square": return p < 0.5 ? 1 : -1;
    case "sawtooth": return 2 * p - 1;
    case "triangle": return 1 - 4 * Math.abs(p - 0.5);
    default: return Math.sin(2 * Math.PI * p);
  }
}

function render(tones) {
  const end = Math.max(...tones.map((t) => (t.delay ?? 0) + t.duration + 0.05));
  const out = new Float32Array(Math.ceil(end * RATE));
  for (const { freq, toFreq, duration, type = "sine", volume = 0.4, delay = 0, attack = 0.008 } of tones) {
    const start = Math.floor(delay * RATE);
    const n = Math.floor((duration + 0.05) * RATE);
    let phase = 0;
    for (let i = 0; i < n && start + i < out.length; i++) {
      const t = i / RATE;
      const f = toFreq ? expRamp(freq, Math.max(20, toFreq), t / duration) : freq;
      phase += f / RATE;
      const v = Math.max(0.0002, volume);
      const g = t < attack ? expRamp(0.0001, v, t / attack) : t < duration ? expRamp(v, 0.0001, (t - attack) / (duration - attack)) : 0;
      out[start + i] += osc(type, phase) * g * MASTER;
    }
  }
  return out;
}

function wav(samples) {
  const buf = Buffer.alloc(44 + samples.length * 2);
  buf.write("RIFF", 0); buf.writeUInt32LE(36 + samples.length * 2, 4); buf.write("WAVE", 8);
  buf.write("fmt ", 12); buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20); buf.writeUInt16LE(1, 22);
  buf.writeUInt32LE(RATE, 24); buf.writeUInt32LE(RATE * 2, 28); buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34);
  buf.write("data", 36); buf.writeUInt32LE(samples.length * 2, 40);
  samples.forEach((s, i) => buf.writeInt16LE(Math.round(Math.max(-1, Math.min(1, s)) * 32767), 44 + i * 2));
  return buf;
}

