/**
 * Writes assets/voice/clips.ts (gitignored, like the recordings) from the files in assets/voice/en: the clip
 * map, plus when each spoken word starts, so the app can highlight the words as Brijo reads them.
 * Word timings come from whisper.cpp, offline. Re-run after adding or re-recording clips:
 *
 *   brew install ffmpeg whisper-cpp
 *   WHISPER_MODEL=/path/to/ggml-base.en.bin node scripts/voice-clips.mjs
 *
 * Without a model the clip map is still written, and lines without timings are highlighted as a whole.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const DIR = "assets/voice";
const model = process.env.WHISPER_MODEL;
const ids = readdirSync(join(DIR, "en"))
  .filter((f) => f.endsWith(".m4a"))
  .map((f) => f.slice(0, -4))
  .sort();

/** [word, start in ms] for each word whisper hears in the clip. */
function wordTimes(id, work) {
  const wav = join(work, `${id}.wav`);
  execFileSync("ffmpeg", ["-loglevel", "error", "-y", "-i", join(DIR, "en", `${id}.m4a`), "-ar", "16000", "-ac", "1", wav]);
  execFileSync("whisper-cli", ["-m", model, "-f", wav, "-ml", "1", "-sow", "-oj", "-np", "-of", join(work, id)], { stdio: "ignore" });
  const { transcription } = JSON.parse(readFileSync(join(work, `${id}.json`), "utf8"));
  return transcription
    .map((s) => [s.text.trim(), s.offsets.from])
    .filter(([w]) => w);
}

const words = {};
if (model && existsSync(model)) {
  const work = mkdtempSync(join(tmpdir(), "voice-"));
  for (const id of ids) words[id] = wordTimes(id, work);
  rmSync(work, { recursive: true });
} else {
  console.warn("No WHISPER_MODEL: writing the clip map without word timings.");
}

const lines = [
  "// Generated by scripts/voice-clips.mjs. Not in git: the recordings are © Rachel Kenyani (see README).",
  "",
  "const clips: Record<string, number> = {",
  ...ids.map((id) => `  "${id}": require("./en/${id}.m4a"),`),
  "};",
  "",
  "/** When each spoken word starts: [word as heard, ms]. */",
  `export const words: Record<string, [string, number][]> = ${JSON.stringify(words)};`,
  "",
  "export default clips;",
  "",
];
writeFileSync(join(DIR, "clips.ts"), lines.join("\n"));
console.log(`Wrote ${ids.length} clips (${Object.keys(words).length} with word timings) to ${DIR}/clips.ts`);
